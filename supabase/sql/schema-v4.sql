-- ① ลูกค้าอัปได้เฉพาะไฟล์ใน "โฟลเดอร์ชื่อเดียวกับบัญชีตัวเอง" (รูปแบบ: <uid>/order/...png)
--    ลูกค้าคนหนึ่งเห็น/อัปเฉพาะโฟลเดอร์ตัวเอง ไม่เกี่ยวโฟลเดอร์คนอื่น
drop policy if exists s_own_write on storage.objects;
create policy s_own_write on storage.objects for insert to authenticated
  with check (bucket_id = 'myrikaka'
              and (storage.foldername(name))[1] = auth.uid()::text);

-- ② ลูกค้า "แก้/ลบ" ไฟล์ที่อัปไปแล้วไม่ได้ → หลักฐานการชำระเงินไม่มีทางถูกลบหลังส่ง
--    (ไม่สร้าง policy update/delete สำหรับลูกค้า = ห้ามโดยปริยาย พนักงานยังจัดการได้เต็มที่ตามเดิม)

-- ③ พนักงานทุกคนยังอัปได้เหมือนเดิมผ่าน policy s_write เดิม (โฟลเดอร์ order/, product/, proof/, state/)

