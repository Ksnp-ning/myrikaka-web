--  วิธีรัน: Supabase Dashboard → SQL Editor → New query → วางทั้งไฟล์ → Run
--  รันซ้ำได้ปลอดภัยเสมอ (ลบ policy เดิมก่อนสร้างใหม่ทุกครั้ง)
